/**
 * Render the workstation stack template platform/workstation/templates/atl-workstation.yaml (03 §4.4) from
 * templates/atl-workstation.src.yaml + bootstrap/user-data.sh (the user data is a Fn::Sub template, embedded as a block
 * scalar). The rendered file is committed: the runner (ATL_OP=workstation-up) deploys it from cloudalbum-infra.zip.
 *   npm run workstation-template -w @atl/infra [-- --check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const WORKSTATION_DIR = path.resolve(HERE, '..', '..', 'workstation');
export const WORKSTATION_TEMPLATE = path.join(WORKSTATION_DIR, 'templates', 'atl-workstation.yaml');

export function renderWorkstationTemplate(): string {
  const src = fs.readFileSync(path.join(WORKSTATION_DIR, 'templates', 'atl-workstation.src.yaml'), 'utf8').replace(/\r\n/g, '\n');
  const userData = fs.readFileSync(path.join(WORKSTATION_DIR, 'bootstrap', 'user-data.sh'), 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '');
  const lines = src.split('\n');
  const i = lines.findIndex((l) => l.trim() === '@@USER_DATA@@');
  if (i < 0) throw new Error('atl-workstation.src.yaml has no @@USER_DATA@@ line');
  const indent = lines[i]!.slice(0, lines[i]!.indexOf('@'));
  const body = userData.split('\n').map((l) => (l ? indent + l : ''));
  const header = [
    '# GENERATED by platform/infra/build/workstation-template.ts from atl-workstation.src.yaml + ../bootstrap/user-data.sh — do not edit.',
    '# Workstation stack atl-ws-<sid> (03 §4.4), deployed by the runner (ATL_OP=workstation-up).',
  ];
  const first = lines.findIndex((l) => !l.startsWith('#'));
  const out = [...header, ...lines.slice(first, i), ...body, ...lines.slice(i + 1)];
  return out.join('\n').replace(/\n*$/, '\n');
}

function main(): void {
  const text = renderWorkstationTemplate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(WORKSTATION_TEMPLATE) ? fs.readFileSync(WORKSTATION_TEMPLATE, 'utf8') : '';
    if (current !== text) {
      console.error('platform/workstation/templates/atl-workstation.yaml is stale: npm run workstation-template -w @atl/infra');
      process.exitCode = 1;
    }
    return;
  }
  fs.writeFileSync(WORKSTATION_TEMPLATE, text);
  console.log(`workstation template → ${path.relative(process.cwd(), WORKSTATION_TEMPLATE)}`);
}

if (process.argv[1] && /workstation-template\.(ts|js)$/.test(process.argv[1])) main();
