/**
 * 服务图标的数据源（docs/platform/09-i18n-and-visual.md「视觉组件」）：把 modules/registry.yaml 与 labs/_catalog/taxonomy.yaml
 * 压缩成 platform/web/src/ui/glyphs/registry.generated.ts，供 <ServiceGlyph>、<ArchDiagram> 在浏览器里使用（SPA 不读 YAML）。
 *
 *   node platform/web/scripts/gen-glyph-registry.mjs           # 重新生成
 *   node platform/web/scripts/gen-glyph-registry.mjs --check   # 只比较，不一致时退出码 1（CI；单元测试也做同样的比较）
 *
 * 每个模块取：组（base / A～F）、AWS 服务名、缩写与短名（taxonomy）、机能（taxonomy 的短句，zh-CN 源语言）、类型，
 * 以及从 requires / soft 推出的依赖（服务 id 与附属服务另生成别名表；与模块 id 同名的服务 id 不做别名）：
 *   - hard：启用本模块就必须存在的模块（requires 条目没有 when，或 when 只写本模块自己的开关且取值属于 ownedValues；
 *     severity: warn 的条目只是提醒，归入 cond）；
 *   - cond：只在某个选项取值下才需要的模块（when 里出现其他键）；
 *   - anyOf：全部由模块组成的“二选一”（例如 waf 的 `cdn | load-balancer`）；含配置项的备选不算（可以不靠模块满足）；
 *   - soft：registry 的 soft 原样保留。
 * need 中的原子：模块 id，或 `VAR=value` 且 VAR 是另一个模块的开关、value 属于它的 ownedValues（如 STORAGE_DRIVER=s3 → storage）；
 * `!=` 与普通配置项不产生依赖。输出只依赖输入内容（键按 registry 顺序），重复运行结果相同。
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

/**
 * @typedef {{ hard: string[]; cond: string[]; anyOf: string[][]; soft: string[] }} GlyphDeps
 * @typedef {{ id: string; group: string; awsService: string; abbr: string; short: string; serviceId: string; fn: string; type: string; deps: GlyphDeps }} GlyphModuleOut
 * @typedef {{ var?: string; ownedValues?: string[]; kind?: string }} RegistrySwitch
 * @typedef {{ when?: Record<string, unknown>; need?: string[]; severity?: string }} RegistryRequire
 * @typedef {{ group: string; awsService: string; function?: string; type: string; switch?: RegistrySwitch; requires?: RegistryRequire[]; soft?: string[] }} RegistryModule
 * @typedef {string | Record<string, string>} TaxonomyText 纯字符串（zh-CN）或本地化对象 { zh-CN, ja, en }
 * @typedef {{ id: string; abbr: string; name: TaxonomyText; short?: TaxonomyText; function?: TaxonomyText; category?: string; module?: string; featureOf?: string }} TaxonomyService
 * @typedef {{ id: string; label: TaxonomyText; token?: string; symbol?: string }} TaxonomyCategory
 */

export const OUTPUT_HEADER =
  '// Generated by platform/web/scripts/gen-glyph-registry.mjs from modules/registry.yaml and labs/_catalog/taxonomy.yaml.\n' +
  '// Do not edit by hand. Regenerate: node platform/web/scripts/gen-glyph-registry.mjs (--check compares only).\n';

/**
 * taxonomy 的文本字段可以是本地化对象 `{ zh-CN, ja, en }`（09 §2，I4）；生成的注册表只取 zh-CN 源语言（各语言的界面文字由
 * visualMessages.ts 与目录 API 提供）。
 * @param {unknown} v @returns {string | undefined}
 */
const zh = (v) => (v && typeof v === 'object' ? /** @type {Record<string, string>} */ (v)['zh-CN'] : /** @type {string | undefined} */ (v));

/**
 * @param {string} registryText modules/registry.yaml
 * @param {string} taxonomyText labs/_catalog/taxonomy.yaml
 * @returns {string} registry.generated.ts 的完整内容
 */
export function buildGlyphRegistrySource(registryText, taxonomyText) {
  /** @type {{ modules: Record<string, RegistryModule> }} */
  const registry = parse(registryText);
  /** @type {{ categories: TaxonomyCategory[]; services: TaxonomyService[] }} */
  const taxonomy = parse(taxonomyText);
  const modules = registry.modules;
  const ids = Object.keys(modules);
  const idSet = new Set(ids);

  /** `VAR=value` → 模块（value 属于该模块开关的 ownedValues）。 */
  /** @type {Map<string, string>} */
  const owned = new Map();
  for (const id of ids) {
    const sw = modules[id].switch;
    if (sw?.var && Array.isArray(sw.ownedValues)) for (const v of sw.ownedValues) owned.set(`${sw.var}=${v}`, id);
  }
  /** @param {string} atom @returns {string | null} */
  const moduleOfAtom = (atom) => {
    const a = atom.trim();
    if (idSet.has(a)) return a;
    if (a.includes('!=')) return null;
    return owned.get(a.replace(/\s+/g, '')) ?? null;
  };

  /** @type {Map<string, TaxonomyService>} */
  const svcByModule = new Map();
  for (const s of taxonomy.services) if (s.module) svcByModule.set(s.module, s);

  /** @type {GlyphModuleOut[]} */
  const out = [];
  for (const id of ids) {
    const m = modules[id];
    const svc = svcByModule.get(id);
    if (!svc) throw new Error(`taxonomy.yaml has no service for module ${id}`);
    /** @type {Set<string>} */
    const hard = new Set();
    /** @type {Set<string>} */
    const cond = new Set();
    /** @type {string[][]} */
    const anyOf = [];
    const ownVar = m.switch?.var;
    const ownValues = new Set((m.switch?.ownedValues ?? []).map(String));
    for (const req of m.requires ?? []) {
      const when = req.when ?? {};
      const keys = Object.keys(when);
      // severity: warn 只是提醒（例如 ALB 建议配 Cognito），不算硬依赖
      const unconditional =
        req.severity !== 'warn' && keys.every((k) => k === ownVar && (ownValues.size === 0 || ownValues.has(String(when[k]))));
      for (const need of req.need ?? []) {
        const alts = String(need).split('|').map((s) => s.trim());
        const mods = alts.map(moduleOfAtom);
        if (alts.length === 1) {
          const dep = mods[0];
          if (dep && dep !== id) (unconditional ? hard : cond).add(dep);
        } else if (mods.every((x) => x !== null)) {
          const group = [...new Set(/** @type {string[]} */ (mods))].filter((x) => x !== id);
          if (group.length > 1 && unconditional) anyOf.push(group);
          else for (const dep of group) cond.add(dep);
        }
      }
    }
    for (const dep of hard) cond.delete(dep);
    out.push({
      id,
      group: m.group,
      awsService: m.awsService,
      abbr: svc.abbr,
      short: zh(svc.short) ?? zh(svc.name) ?? '',
      serviceId: svc.id,
      fn: zh(svc.function) ?? m.function ?? '',
      type: m.type,
      deps: { hard: [...hard].sort(), cond: [...cond].sort(), anyOf, soft: [...(m.soft ?? [])] },
    });
  }

  /** 服务 id（taxonomy）与附属服务 → 模块（ebs → ec2、shield → waf …）。 */
  /** @type {Record<string, string>} */
  const alias = {};
  /** @type {Map<string, TaxonomyService>} */
  const svcById = new Map(taxonomy.services.map((s) => [s.id, s]));
  for (const s of taxonomy.services) {
    /** @type {TaxonomyService | undefined} */
    let cur = s;
    for (let hops = 0; cur && !cur.module && cur.featureOf && hops < 4; hops++) cur = svcById.get(cur.featureOf);
    // 与模块 id 同名的服务 id 不做别名（taxonomy 的 config 是 AWS Config = compliance，而模块 config 是 Parameter Store）
    if (cur?.module && s.id !== cur.module && !idSet.has(s.id)) alias[s.id] = cur.module;
  }

  const groups = taxonomy.categories.map((c) => ({ id: c.id, label: zh(c.label) ?? c.id, symbol: c.symbol ?? 'square' }));
  const lines = [
    OUTPUT_HEADER,
    "export type GlyphGroupId = 'base' | 'A' | 'B' | 'C' | 'D' | 'E' | 'F';",
    '',
    'export interface GlyphDeps {',
    '  /** 启用本模块就必须存在的模块。 */',
    '  readonly hard: readonly string[];',
    '  /** 只在某个选项取值下需要的模块。 */',
    '  readonly cond: readonly string[];',
    '  /** 全部由模块组成的备选（满足其一即可）。 */',
    '  readonly anyOf: readonly (readonly string[])[];',
    '  readonly soft: readonly string[];',
    '}',
    '',
    'export interface GlyphModule {',
    '  readonly id: string;',
    '  readonly group: GlyphGroupId;',
    '  /** AWS 服务名（不翻译，I3）。 */',
    '  readonly awsService: string;',
    '  readonly abbr: string;',
    '  /** 短名（产品名，不翻译）。 */',
    '  readonly short: string;',
    '  /** taxonomy 的服务 id。 */',
    '  readonly serviceId: string;',
    '  /** 机能短句（zh-CN 源语言；界面经 visual.fn.<id> 键取译文）。 */',
    '  readonly fn: string;',
    '  readonly type: string;',
    '  readonly deps: GlyphDeps;',
    '}',
    '',
    'export interface GlyphGroupDef {',
    '  readonly id: GlyphGroupId;',
    '  /** zh-CN 源语言；界面经 visual.group.<id> 键取译文。 */',
    '  readonly label: string;',
    '  readonly symbol: string;',
    '}',
    '',
    `export const GLYPH_GROUPS: readonly GlyphGroupDef[] = [\n${groups.map((g) => `  ${JSON.stringify(g)},`).join('\n')}\n];`,
    '',
    `export const GLYPH_MODULES: readonly GlyphModule[] = [\n${out.map((m) => `  ${JSON.stringify(m)},`).join('\n')}\n];`,
    '',
    `export const GLYPH_SERVICE_ALIAS: Readonly<Record<string, string>> = ${JSON.stringify(alias, Object.keys(alias).sort(), 2)};`,
    '',
  ];
  return lines.join('\n');
}

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../../..');
export const OUTPUT_PATH = path.join(REPO, 'platform/web/src/ui/glyphs/registry.generated.ts');

/** @param {string[]} argv */
function main(argv) {
  const src = buildGlyphRegistrySource(
    readFileSync(path.join(REPO, 'modules/registry.yaml'), 'utf8'),
    readFileSync(path.join(REPO, 'labs/_catalog/taxonomy.yaml'), 'utf8'),
  );
  let current = '';
  try {
    current = readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    current = '';
  }
  if (argv.includes('--check')) {
    if (current.replace(/\r\n/g, '\n') !== src) {
      console.error(`${path.relative(REPO, OUTPUT_PATH)} is out of date: run node platform/web/scripts/gen-glyph-registry.mjs`);
      process.exitCode = 1;
    } else console.log('glyph registry is up to date');
    return;
  }
  if (current.replace(/\r\n/g, '\n') !== src) writeFileSync(OUTPUT_PATH, src);
  console.log(`wrote ${path.relative(REPO, OUTPUT_PATH)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
