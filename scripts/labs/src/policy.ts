/**
 * `labs:policy` (04 §2.5, §5.7): the `service:action` pairs that the content's `aws-readonly` checks and corroborations
 * use, intersected with the base whitelist and converted to IAM actions — the generated read-only statement of
 * ATLVerifierRole (01's policy generator merges it). Actions outside the whitelist fail.
 */
import { expandChecks } from './checks.js';
import { fullCards, type ContentSet } from './content.js';
import { iamActionOf, isAllowed } from './allowlist.js';

export interface PolicyResult {
  sdkActions: string[];
  iamActions: string[];
  rejected: { card: string; check: string; action: string }[];
  document: Record<string, unknown>;
}

export function verifierPolicy(set: ContentSet): PolicyResult {
  const sdk = new Set<string>();
  const rejected: PolicyResult['rejected'] = [];
  const consider = (card: string, check: string, service: unknown, action: unknown) => {
    const s = String(service);
    const a = String(action);
    if (!isAllowed(s, a)) rejected.push({ card, check, action: `${s}:${a}` });
    else sdk.add(`${s}:${a}`);
  };
  for (const card of fullCards(set)) {
    const ex = expandChecks(set, card);
    for (const [id, d] of Object.entries(ex.checks)) {
      if (d.type === 'aws-readonly') consider(card.id, id, d.service, d.action);
      for (const c of (d.corroborate as Record<string, unknown>[] | undefined) ?? []) if (c.via === 'aws-readonly') consider(card.id, `${id}/${String(c.id)}`, c.service, c.action);
    }
  }
  const sdkActions = [...sdk].sort();
  const iamActions = [...new Set(sdkActions.map((x) => iamActionOf(x.split(':')[0]!, x.split(':')[1]!)))].sort();
  return {
    sdkActions,
    iamActions,
    rejected,
    document: {
      '//': 'Generated by npm run labs:policy (scripts/labs) from the aws-readonly checks of labs/ (04 §5.7). Do not edit.',
      Version: '2012-10-17',
      Statement: [{ Sid: 'AtlContentReadOnly', Effect: 'Allow', Action: iamActions, Resource: '*' }],
      'x-atl-sdk-actions': sdkActions,
    },
  };
}
