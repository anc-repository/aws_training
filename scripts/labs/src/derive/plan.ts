/**
 * The start-state plan (06 PM-33 `cloudalbum.plan/v1`), its digest and the generated profile file
 * `profiles/atl/<card-id>/<variant>.env` (06 PM-33 “档位文件”, 05 §8.5).
 *
 * The digest object follows PM-33 step 11: `{ schema, card, variant, registryVersion, modules: [by id {id, kind, set,
 * params, value}], platform, baseParams, extraStacks: [{id, region}] }`, RFC 8785 canonical JSON, SHA-256. Explanatory
 * fields (`because`, `order`, `seeds`, `basis`) are not part of it. `profileDigest()` rebuilds the same object from a
 * profile file (what `plan --profile` does at run time, PM-32), so DRV-10 can compare both entry points.
 */
import crypto from 'node:crypto';
import { canonicalJson, startProfileName } from '@atl/shared';

export const PLAN_SCHEMA = 'cloudalbum.plan/v1';

export type PlanBasis = 'base' | 'credential' | 'closure' | 'precursor' | 'context' | 'single';
export type Scalar = string | number | boolean;

export interface PlanEntry {
  id: string;
  kind: 'module' | 'local' | 'runtime';
  basis: PlanBasis;
  set?: Record<string, string>;
  params?: Record<string, string>;
  value?: string;
  because?: string[];
}

export interface PlanOutput {
  schema: typeof PLAN_SCHEMA;
  deriver: 'scripts/module' | 'reference';
  registryVersion: string;
  toolkitVersion: string;
  card: string;
  variant: string;
  profileName: string;
  start: PlanEntry[];
  targets: { id: string; driver: string; fromDriver?: string }[];
  branches: Record<string, { choose: string }>;
  platform: { 'preview.directHttps': 'on' | 'off' };
  baseParams: Record<string, string>;
  warnings: string[];
  errors: string[];
  order: string[];
  seeds: string[];
  extraStacks: { id: string; region: string }[];
  /** module id → modules that must be wired before it (targets only; DRV-7) */
  targetDeps: Record<string, string[]>;
  digest: string;
}

export function str(v: Scalar | undefined | null): string {
  return v === undefined || v === null ? '' : String(v);
}

export function strMap(m: Record<string, Scalar> | undefined): Record<string, string> | undefined {
  if (!m || !Object.keys(m).length) return undefined;
  return Object.fromEntries(Object.entries(m).map(([k, v]) => [k, str(v)]));
}

export interface DigestInput {
  card: string;
  variant: string;
  registryVersion: string;
  start: readonly PlanEntry[];
  platform: { 'preview.directHttps': 'on' | 'off' };
  baseParams: Record<string, string>;
  extraStacks: readonly { id: string; region: string }[];
}

export function digestObject(d: DigestInput): Record<string, unknown> {
  const modules = d.start
    .filter((e) => e.basis !== 'base')
    .map((e) => ({
      id: e.id,
      kind: e.kind,
      set: e.set ?? {},
      params: e.params ?? {},
      // scripts/module digestObject: `value: m.value ?? null` for every entry (06 PM-33); runtime values are typed the way
      // scripts/module parses PROFILE_RUNTIME (true / false / numbers), so a lab.yaml `value: true` and its profile round trip agree
      value: e.value === undefined ? null : e.kind === 'runtime' ? runtimeValue(e.value) : e.value,
    }))
    .sort((a, b) => (a.id === b.id ? (a.kind < b.kind ? -1 : 1) : a.id < b.id ? -1 : 1));
  return {
    schema: PLAN_SCHEMA,
    card: d.card,
    variant: d.variant,
    registryVersion: d.registryVersion,
    modules,
    platform: d.platform,
    baseParams: d.baseParams,
    extraStacks: d.extraStacks.map((x) => ({ id: x.id, region: x.region })),
  };
}

/** scripts/module plan-start.ts runtimeValue(): the typed form of a PROFILE_RUNTIME value */
export function runtimeValue(v: string): Scalar {
  if (v === 'true') return true;
  if (v === 'false') return false;
  if (/^-?[0-9]+(\.[0-9]+)?$/.test(v)) return Number(v);
  return v;
}

export function planDigest(d: DigestInput): string {
  return `sha256:${crypto.createHash('sha256').update(canonicalJson(digestObject(d))).digest('hex')}`;
}

