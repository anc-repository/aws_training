// profile file

const kv = (m: Record<string, string> | undefined) =>
  Object.entries(m ?? {})
    .map(([k, v]) => `${k}=${v}`)
    .join(',');

export function renderProfile(plan: PlanOutput, labVersion: string): string {
  const modules = plan.start.filter((e) => e.kind === 'module' && e.basis !== 'base');
  const locals = plan.start.filter((e) => e.kind === 'local');
  const runtime = plan.start.filter((e) => e.kind === 'runtime');
  const drivers: Record<string, string> = {};
  const params: string[] = [];
  for (const m of modules) {
    Object.assign(drivers, m.set ?? {});
    for (const [k, v] of Object.entries(m.params ?? {})) params.push(`${m.id}.${k}=${v}`);
  }
  const localSettings: Record<string, string> = {};
  for (const l of locals) Object.assign(localSettings, l.set ?? {});
  const lines = [
    `# profiles/${plan.profileName}.env — generated by labs:build (scripts/labs), do not edit (05 §8.5, 06 PM-33)`,
    `PROFILE_NAME=${plan.profileName}`,
    'PROFILE_KIND=atl-start',
    `PROFILE_CARD=${plan.card}`,
    `PROFILE_VARIANT=${plan.variant}`,
    'PROFILE_EXTENDS=l0-ec2',
    `PROFILE_MODULES=${modules.map((m) => m.id).join(',')}`,
    `PROFILE_DRIVERS=${kv(drivers)}`,
    `PROFILE_LOCAL_SETTINGS=${kv(localSettings)}`,
    `PROFILE_RUNTIME=${runtime.map((r) => `${r.id}=${r.value ?? ''}`).join(',')}`,
    `PROFILE_PARAMS=${params.join(',')}`,
    `PROFILE_BASE_PARAMS=${kv(plan.baseParams)}`,
    `PROFILE_SEEDS=${plan.seeds.join(',')}`,
    `PROFILE_EXTRA_STACKS=${plan.extraStacks.map((x) => `${x.id}@${x.region}`).join(',')}`,
    `PROFILE_PLATFORM=preview.directHttps=${plan.platform['preview.directHttps']}`,
    `PROFILE_PLAN_DIGEST=${plan.digest}`,
    `PROFILE_REGISTRY_VERSION=${plan.registryVersion}`,
    `PROFILE_SOURCE=labs/${plan.card}/lab.yaml@${labVersion}`,
  ];
  return `${lines.join('\n')}\n`;
}

export function parseProfile(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i > 0) out[line.slice(0, i)] = line.slice(i + 1);
  }
  return out;
}

function parseKv(s: string | undefined): [string, string][] {
  if (!s) return [];
  return s
    .split(',')
    .filter(Boolean)
    .map((p) => {
      const i = p.indexOf('=');
      return [p.slice(0, i), p.slice(i + 1)] as [string, string];
    });
}

/**
 * Rebuilds the digest from a profile file (the run-time `plan --profile` entry point, 06 PM-32). `ownerOfKey` maps
 * an env key to its module (registry ownsEnv / switch variable).
 */
export function profileDigest(text: string, registryVersion: string, ownerOfKey: (key: string) => string | undefined): { digest: string; declared: string } {
  const p = parseProfile(text);
  const start: PlanEntry[] = [];
  const byModule = new Map<string, PlanEntry>();
  for (const id of (p.PROFILE_MODULES ?? '').split(',').filter(Boolean)) {
    const e: PlanEntry = { id, kind: 'module', basis: 'closure' };
    byModule.set(id, e);
    start.push(e);
  }
  for (const [k, v] of parseKv(p.PROFILE_DRIVERS)) {
    const owner = ownerOfKey(k);
    const e = owner ? byModule.get(owner) : undefined;
    if (!e) continue;
    e.set = { ...(e.set ?? {}), [k]: v };
  }
  for (const pv of (p.PROFILE_PARAMS ?? '').split(',').filter(Boolean)) {
    const dot = pv.indexOf('.');
    const eq = pv.indexOf('=');
    const e = byModule.get(pv.slice(0, dot));
    if (e) e.params = { ...(e.params ?? {}), [pv.slice(dot + 1, eq)]: pv.slice(eq + 1) };
  }
  const locals = new Map<string, PlanEntry>();
  for (const [k, v] of parseKv(p.PROFILE_LOCAL_SETTINGS)) {
    const owner = ownerOfKey(k) ?? k;
    const e = locals.get(owner) ?? { id: owner, kind: 'local' as const, basis: 'single' as const };
    e.set = { ...(e.set ?? {}), [k]: v };
    locals.set(owner, e);
  }
  start.push(...locals.values());
  for (const [k, v] of parseKv(p.PROFILE_RUNTIME)) start.push({ id: k, kind: 'runtime', basis: 'single', value: v });
  const directHttps = (p.PROFILE_PLATFORM ?? '').endsWith('=off') ? 'off' : 'on';
  const extraStacks = (p.PROFILE_EXTRA_STACKS ?? '')
    .split(',')
    .filter(Boolean)
    .map((x) => {
      const [id, region] = x.split('@');
      return { id: id ?? '', region: region ?? '' };
    });
  const digest = planDigest({
    card: p.PROFILE_CARD ?? '',
    variant: p.PROFILE_VARIANT ?? '',
    registryVersion,
    start,
    platform: { 'preview.directHttps': directHttps },
    baseParams: Object.fromEntries(parseKv(p.PROFILE_BASE_PARAMS)),
    extraStacks,
  });
  return { digest, declared: p.PROFILE_PLAN_DIGEST ?? '' };
}

export function profileNameOf(card: string, variant: string): string {
  return startProfileName(card, variant);
}
