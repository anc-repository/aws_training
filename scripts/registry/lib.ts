/**
 * Shared helpers for `npm run gen:registry` (build.ts) and `npm run registry:check` (check.ts).
 * Runs under tsx on the operator / CI machine; never shipped to EC2.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv, type ErrorObject } from 'ajv';
import { parse as parseYaml } from 'yaml';
import type { RegistryDocument } from '@cloudalbum/contracts';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const REGISTRY_YAML = path.join(REPO_ROOT, 'modules', 'registry.yaml');
export const REGISTRY_SCHEMA = path.join(REPO_ROOT, 'modules', 'registry.schema.json');
export const GENERATED_TS = path.join(REPO_ROOT, 'packages', 'contracts', 'src', 'generated', 'registry.ts');

export interface LoadedRegistry {
  doc: RegistryDocument;
  text: string;
  sha256: string;
}

export function loadRegistry(file = REGISTRY_YAML): LoadedRegistry {
  const text = readFileSync(file, 'utf8');
  const raw = parseYaml(text, { version: '1.2', prettyErrors: true }) as unknown;
  const doc = normalizeRegistry(raw as RegistryDocument);
  const sha256 = createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
  return { doc, text, sha256 };
}

/** `when` / `selfHosted.match` 的标量一律转成字符串（YAML 中写成 true / 1 时也能与 env 比较）。 */
export function normalizeRegistry(doc: RegistryDocument): RegistryDocument {
  const stringify = (o: Record<string, unknown> | undefined) => {
    if (!o) return;
    for (const k of Object.keys(o)) {
      const v = o[k];
      if (v === null || v === undefined) o[k] = '';
      else if (typeof v !== 'string') o[k] = String(v);
    }
  };
  for (const m of Object.values(doc.modules ?? {})) {
    for (const r of m.requires ?? []) stringify(r.when);
    for (const c of m.conflicts ?? []) stringify(c.when);
    for (const i of m.injects ?? []) stringify(i.when);
    for (const e of m.internalEndpoints ?? []) stringify(e.when);
    for (const s of m.stacks ?? []) if (s.when && typeof s.when === 'object') stringify(s.when);
    for (const v of Object.values(m.baseParams ?? {})) if (typeof v === 'object') stringify(v.when);
    if (m.selfHosted) stringify(m.selfHosted.match);
  }
  return doc;
}

export function validateRegistrySchema(doc: unknown): string[] {
  const schema = JSON.parse(readFileSync(REGISTRY_SCHEMA, 'utf8')) as object;
  const ajv = new Ajv({ allErrors: true, strict: false });
  const validate = ajv.compile(schema);
  if (validate(doc)) return [];
  return (validate.errors ?? []).map((e: ErrorObject) => {
    const where = e.instancePath || '(root)';
    const extra = e.params && Object.keys(e.params).length ? ` ${JSON.stringify(e.params)}` : '';
    return `${where}: ${e.message ?? 'invalid'}${extra}`;
  });
}

export function renderGenerated(loaded: LoadedRegistry): string {
  const json = JSON.stringify(loaded.doc, null, 2);
  return [
    '// AUTO-GENERATED by scripts/registry/build.ts from modules/registry.yaml — DO NOT EDIT.',
    '// Regenerate with `npm run gen:registry`; `npm run registry:check` fails when this file is stale.',
    '/* eslint-disable */',
    "import type { RegistryDocument } from '../registry-types.js';",
    '',
    `export const REGISTRY_SOURCE_SHA256 = '${loaded.sha256}';`,
    '',
    `export const REGISTRY_DOCUMENT: RegistryDocument = ${json};`,
    '',
  ].join('\n');
}
